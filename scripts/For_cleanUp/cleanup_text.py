def ends_cont(text: str) -> bool:
    t = text.strip()
    if not t:
        return False
    if t[-1] in "—–-":
        return True
    if t[-1] in ",;:":
        return True
    # Последнее слово должно быть отдельным, а не частью сокращения
    # вроде «б/у» или «т.е.».
    m = re.search(rf"(?:^|\s)([{CYR}{LAT}]+)$", t)
    if m and m.group(1).lower() in CONT_WORDS:
        return True
    return False


def starts_cont(text: str) -> bool:
    t = text.strip()
    if not t:
        return False
    if t[0] in "—–-/":
        return True
    return t[0].isalpha() and t[0].islower()


def last_nonempty(cells: list[str]) -> str:
    for c in reversed(cells):
        if c.strip():
            return c.strip()
    return ""


def split_row(line: str) -> list[str]:
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|"):
        s = s[:-1]
    return [c.strip() for c in s.split("|")]


def is_separator(cells: list[str]) -> bool:
    return all(re.fullmatch(r":?-{2,}:?", c) for c in cells if c != "")


def merge_table_rows(rows: list[list[str]]) -> list[list[str]]:
    groups: list[list[list[str]]] = []
    cur: list[list[str]] = []
    # waiting — в текущей группе ещё нет строки с непустой первой ячейкой,
    # то есть группа началась с продолжения и ждёт свою подпись.
    waiting = False
    # started_incomplete — группа началась со строки без подписи, значит это
    # многострочная строка, а не набор самостоятельных строк.
    started_incomplete = False
    # Значение первой ячейки, повторяющееся в нескольких строках, — это
    # категория («Офлайн», «Онлайн»), а не разорванная подпись. Такие строки
    # склеивать нельзя, иначе несколько логических строк сольются в одну.
    first_counts = Counter(r[0].strip() for r in rows if r[0].strip())
    for idx, r in enumerate(rows):
        if not cur:
            cur = [r]
            waiting = not r[0].strip()
            started_incomplete = waiting
            continue
        prev = cur[-1]
        c1 = r[0].strip()
        p1 = prev[0].strip()
        if not c1:
            if waiting or idx == len(rows) - 1:
                cur.append(r)
                continue
            # Пустая первая ячейка — продолжение либо предыдущей строки,
            # либо следующей. Если хотя бы одна ячейка начинается со
            # строчной буквы, тире или слэша, строка продолжает предыдущую.
            if any(
                (c[:1].islower() and not DOMAIN_LIKE.match(c)) or c[:1] in "—–-/"
                for c in r
                if c.strip()
            ):
                cur.append(r)
            else:
                groups.append(cur)
                cur = [r]
                waiting = True
                started_incomplete = True
            continue
        if waiting:
            cur.append(r)
            waiting = False
            continue
        # Подпись, разорванная по строкам: предыдущая ячейка — одно слово,
        # а следующая строка начинается со строчной буквы, то есть
        # продолжает ту же подпись. Склеивать можно только тогда, когда
        # строка действительно многострочная: группа началась со строки без
        # подписи, либо предыдущая строка оборвана (какая-то её ячейка
        # кончается союзом, предлогом или тире). Иначе две полные строки с
        # разными значениями («Пекарь» и «Владелец/ управляющий») слились бы
        # в одну. Повторяющееся значение первой ячейки — это категория
        # («Офлайн»), а не разорванная подпись, поэтому такие строки тоже
        # не склеиваются.
        prev_incomplete = any(ends_cont(c) for c in prev if c.strip())
        wrapped_label = (
            len(p1.split()) == 1
            and first_counts.get(c1, 0) < 2
            and (started_incomplete or prev_incomplete)
            and any(c[:1].islower() for c in r if c.strip())
        )
        if ends_cont(p1) or starts_cont(c1) or wrapped_label:
            cur.append(r)
            continue
        groups.append(cur)
        cur = [r]
        started_incomplete = False
    if cur:
        groups.append(cur)

    merged: list[list[str]] = []
    for g in groups:
        ncol = max(len(r) for r in g)
        cells = []
        for i in range(ncol):
            parts = [r[i] for r in g if i < len(r) and r[i].strip()]
            cells.append(" ".join(parts))
        merged.append(cells)
    return merged


def expand_row(cells: list[str], ncol: int) -> list[list[str]]:
    """Разбивает строку, в которую склеились несколько логических строк."""
    if ncol < 2:
        return [cells]
    while len(cells) > ncol and cells[ncol] == "":
        head, cells = cells[:ncol], cells[ncol + 1 :]
        return [head] + expand_row(cells, ncol)
    return [cells]


def split_into_tables(block: list[str]) -> list[tuple[list[str], list[str]]]:
    """Делит слипшийся блок строк на отдельные таблицы по строкам-разделителям.

    В исходнике две таблицы иногда идут подряд без пустой строки, поэтому
    разделитель второй таблицы оказывается внутри одного блока.
    """
    tables: list[tuple[list[str], list[str]]] = []
    pending: list[str] = []
    for line in block:
        if is_separator(split_row(line)):
            if pending:
                header = pending.pop()
                if tables:
                    tables[-1][1].extend(pending)
                tables.append((header, []))
                pending = []
        else:
            pending.append(line)
    if pending:
        if tables:
            tables[-1][1].extend(pending)
        else:
            tables.append(([], pending))
    return tables


def repair_tables(text: str) -> str:
    lines = text.split("\n")
    out: list[str] = []
    i = 0
    while i < len(lines):
        if not lines[i].startswith("|"):
            out.append(lines[i])
            i += 1
            continue
        j = i
        while j < len(lines) and lines[j].startswith("|"):
            j += 1
        for header_line, body_lines in split_into_tables(lines[i:j]):
            if not header_line:
                out.extend(body_lines)
                continue
            header = split_row(header_line)
            ncol = len(header)
            rows: list[list[str]] = []
            for b in body_lines:
                rows.extend(expand_row(split_row(b), ncol))
            merged = merge_table_rows(rows)
            out.append("|" + "|".join(header) + "|")
            out.append("|" + "|".join("---" for _ in range(ncol)) + "|")
            for m in merged:
                m = (m + [""] * ncol)[:ncol]
                out.append("|" + "|".join(m) + "|")
        i = j
    return "\n".join(out)


def separate_adjacent_tables(text: str) -> str:
    """Разделяет склеенные таблицы пустой строкой.

    В исходнике две таблицы иногда идут подряд без пустой строки: последняя
    строка первой таблицы, затем шапка второй. Для markdown это одна таблица
    с лишней строкой-шапкой в середине, поэтому перед шапкой второй таблицы
    вставляется пустая строка. Иначе при нарезке две таблицы попадут в один
    чанк с чужой шапкой посередине.
    """
    lines = text.split("\n")
    out: list[str] = []
    i = 0
    splits = 0
    while i < len(lines):
        if not lines[i].startswith("|"):
            out.append(lines[i])
            i += 1
            continue
        j = i
        while j < len(lines) and lines[j].startswith("|"):
            j += 1
        block = lines[i:j]
        seps = [k for k, l in enumerate(block) if is_separator(split_row(l))]
        if len(seps) <= 1:
            out.extend(block)
        else:
            start = 0
            for s in seps[1:]:
                header_idx = s - 1
                out.extend(block[start:header_idx])
                out.append("")
                start = header_idx
                splits += 1
            out.extend(block[start:])
        i = j
    if splits != 13:
        fail(f"склеенных таблиц разделено {splits}, ожидалось 13")
    return "\n".join(out)


