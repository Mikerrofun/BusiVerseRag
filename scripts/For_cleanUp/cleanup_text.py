def fail(msg: str) -> None:
    print(f"ОШИБКА: {msg}", file=sys.stderr)
    sys.exit(1)


def sub_once(text: str, old: str, new: str, label: str) -> str:
    n = text.count(old)
    if n != 1:
        fail(f"{label}: ожидалось 1 вхождение, найдено {n}: {old[:90]!r}")
    return text.replace(old, new)


def sub_all(text: str, old: str, new: str, label: str, expect: int | None = None) -> str:
    n = text.count(old)
    if n == 0:
        fail(f"{label}: не найдено: {old[:90]!r}")
    if expect is not None and n != expect:
        fail(f"{label}: ожидалось {expect} вхождений, найдено {n}")
    return text.replace(old, new)


