def drop_stray_pipes(text: str) -> str:
    """Убирает одиночные строки из одного символа '|' — следы сломанных таблиц."""
    lines = text.split("\n")
    kept = [l for l in lines if not re.fullmatch(r"\|[ \t]*", l)]
    removed = len(lines) - len(kept)
    if removed == 0:
        fail("одиночные '|' не найдены — проверьте шаблон")
    return "\n".join(kept)


