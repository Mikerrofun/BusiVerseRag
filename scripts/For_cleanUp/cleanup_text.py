# Кириллица <-> латиница без пробела: всегда нужен пробел.
# Исключение — слитные названия продуктов, которые пишутся без пробела.
CYR_LAT_EXCEPTIONS = ["ЮKassa"]

CYR = "А-Яа-яЁё"
LAT = "A-Za-z"

# Домен («hh.ru») начинается со строчной буквы, но фразы не продолжает.
DOMAIN_LIKE = re.compile(r"^[a-z]{2,}\.[a-z]{2,}")


def fix_cyr_lat_glue(text: str) -> str:
    placeholders: dict[str, str] = {}
    for i, token in enumerate(CYR_LAT_EXCEPTIONS):
        ph = f"\x00EX{i}\x00"
        placeholders[ph] = token
        text = text.replace(token, ph)
    text = re.sub(rf"([{CYR}])([{LAT}])", r"\1 \2", text)
    text = re.sub(rf"([{LAT}])([{CYR}])", r"\1 \2", text)
    for ph, token in placeholders.items():
        text = text.replace(ph, token)
    return text


def fix_spacing(text: str) -> str:
    """Убирает следы <br> внутри слов и диапазонов.

    Перенос строки внутри слова («Ростов-на-<br>Дону») после снятия <br>
    превращается в лишний пробел. Такие пробелы убираются после дефиса,
    тире и перед знаком препинания.
    """
    text = re.sub(rf"([{CYR}{LAT}0-9])- ([{CYR}{LAT}0-9])", r"\1-\2", text)
    text = re.sub(r"([0-9])– ([0-9])", r"\1–\2", text)
    # Перенос строки после слэша («Триггер/<br>время») даёт «Триггер/ время».
    # Пробел перед слэшем не трогаем: «Причина / итог» — осознанный разделитель.
    text = re.sub(r"([^\s/])/ ([^\s/])", r"\1/\2", text)
    text = re.sub(rf"([{CYR}{LAT}0-9])—", r"\1 —", text)
    text = re.sub(rf"([{CYR}{LAT}0-9]) ([,.])", r"\1\2", text)
    return text


def mechanical_cleanup(text: str) -> str:
    # Шаг 1. Снять обёртку <u>.
    text = text.replace("<u>", "").replace("</u>", "")

    # Шаг 3. Явные правки OCR-склеек — до снятия <br>, чтобы шаблоны
    # с переносами внутри ячеек совпадали точно.
    for old, new, label in GLUE_FIXES:
        text = sub_all(text, old, new, label)

    # Шаг 1. Снять <br>: внутри ячейки это перенос строки, поэтому пробел.
    text = text.replace("<br>", " ")

    # Шаг 3. Кириллица <-> латиница без пробела.
    text = fix_cyr_lat_glue(text)
    # Пропущенный пробел после запятой/точки с запятой перед буквой.
    text = re.sub(rf"([,;])([{CYR}{LAT}])", r"\1 \2", text)

    # Шаг 3. Следы <br> внутри слов и диапазонов.
    text = fix_spacing(text)

    # Шаг 2. Нормализовать пробелы.
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r" *\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text


